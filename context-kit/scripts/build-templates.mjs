import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const templatesRoot = resolve(projectRoot, 'kit-templates');
const outputPath = resolve(projectRoot, 'src/app/kit/templates.generated.ts');

async function collectFiles(directory) {
  let entries;

  try {
    entries = await readdir(directory, { withFileTypes: true });
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      return [];
    }
    throw error;
  }

  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) {
      continue;
    }

    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(path)));
    } else if (entry.isFile()) {
      files.push(path);
    }
  }
  return files;
}

const files = (await collectFiles(templatesRoot)).sort((left, right) => left.localeCompare(right));
const templates = {};

for (const path of files) {
  const key = relative(templatesRoot, path).split(sep).join('/');
  templates[key] = await readFile(path, 'utf8');
}

const source = `// Generated by scripts/build-templates.mjs. Do not edit.\nexport const TEMPLATES: Record<string, string> = ${JSON.stringify(templates, null, 2)};\n`;
await writeFile(outputPath, source, 'utf8');
